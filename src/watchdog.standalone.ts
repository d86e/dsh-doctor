function guessPkg(spec) {
  if (!spec) return 'unknown'
  const s = String(spec).replace(/^node:/, '')
  const parts = s.split('/')
  if (s.startsWith('@') && parts.length >= 2) return parts[0] + '/' + parts[1]
  return parts[0]
}

/**
 * Guess a package id from a file path. The plugin-file-missing pattern
 * captures absolute-ish paths like
 *   /Users/x/.dsh/node_modules/@scope/dsh-missing/lib/index.js
 * and we want the segment after the last node_modules: @scope/dsh-missing.
 * Until v0.2.22 this function was referenced by the pattern table but
 * never defined — every plugin-file-missing triage threw a
 * ReferenceError inside the standalone watchdog.
 */
function guessPkgFromPath(p) {
  if (!p) return 'unknown'
  const s = String(p)
  const nm = s.match(/node_modules[\/](?:@([^\/]*)\/)?([^\/]*)/)
  if (nm && (nm[1] || nm[2])) {
    if (nm[1] && nm[2]) return '@' + nm[1] + '/' + nm[2]
    return nm[2] || (nm[1] ? '@' + nm[1] : 'unknown')
  }
  return guessPkg(s)
}

// True streaming tail: read the file in chunks from the end until we have
// at least maxLines lines, or we hit the start of the file. Handles large
// log files (multi-hundred-MB) without slurping the whole thing into memory.
// Returns the lines oldest-first, capped at maxLines.
function tailFileByLines(file, maxLines) {
  const cap = Math.max(1, maxLines | 0)
  let fd
  try { fd = fs.openSync(file, 'r') } catch (_) { return [] }
  try {
    const stat = fs.fstatSync(fd)
    const size = stat.size
    if (size === 0) return []
    // Read in 64 KiB chunks from the end. Keep accumulating until we
    // have seen more than cap newlines OR we reach the start of the file.
    const CHUNK = 64 * 1024
    const buf = Buffer.alloc(CHUNK)
    let pos = size
    let pending = ''
    let lines = []
    let stop = false
    while (pos > 0 && !stop) {
      const want = Math.min(CHUNK, pos)
      pos -= want
      const n = fs.readSync(fd, buf, 0, want, pos)
      if (n <= 0) break
      const chunk = buf.slice(0, n).toString('utf8') + pending
      // Split on \n; last element is either '' (clean boundary) or the
      // partial first line of this chunk that we'll prepend on next iter.
      const parts = chunk.split('\n')
      pending = parts.shift() // the incomplete leading line
      for (let i = parts.length - 1; i >= 0; i--) {
        const line = parts[i]
        if (line.length === 0) continue
        lines.unshift(line)
        if (lines.length > cap) { lines.shift(); stop = true; break }
      }
    }
    if (!stop && pending && pending.length > 0) {
      lines.unshift(pending)
      while (lines.length > cap) lines.shift()
    }
    return lines
  } catch (_) { return [] }
  finally { try { fs.closeSync(fd) } catch (_) {} }
}

function triage(buf) {
  const joined = buf.join('\n')
  const sorted = [...PATTERNS].sort((a, b) => b.pri - a.pri)
  for (const p of sorted) {
    const m = joined.match(p.re)
    if (m) return Object.assign({ matched: p.id }, p.act(m))
  }
  return { matched: null, kind: 'safe-mode', reason: 'no-pattern-matched' }
}

// ---------- health probe ------------------------------------------------------

/**
 * One HTTP GET against a path on dsh web. Resolves true ONLY on a 200.
 * Shared by probe() so / and /health use identical timeout + error
 * handling.
 */
function probePath(p) {
  return new Promise((resolve) => {
    let done = false
    const settle = (v) => { if (!done) { done = true; resolve(v) } }
    const req = http.request({
      host: '127.0.0.1',
      port: WEB_PORT,
      path: p,
      method: 'GET',
      timeout: 2000,
    }, (res) => {
      // Drain the body then settle on the status. Do NOT resolve before
      // draining or the socket can hang open across ticks.
      const code = res.statusCode
      res.resume()
      res.once('end', () => settle(code === 200))
      // Belt-and-braces: if the server keeps the connection open without
      // sending an end, the request timeout below will destroy us so we
      // never hang a tick.
    })
    req.on('timeout', () => { req.destroy(); settle(false) })
    req.on('error',   () => settle(false))
    req.end()
  })
}

/**
 * Is dsh web healthy? Healthy = EITHER the GUI shell at / answers 200
 * OR a semantic /health route answers 200.
 *
 * Why two: dsh web historically exposed no /health route, so probing
 * /health alone (the pre-v0.2.27 behavior) 404'd on a perfectly healthy
 * GUI — the watchdog concluded "alive but broken", triaged an empty
 * log, and downgrade-stormed into safe-mode on every incident. The /
 * probe catches the GUI actually being served; the /health probe stays
 * for forward-compat in case a future dsh adds a real health endpoint.
 */
function probe() {
  // Health is the OR of two independent probes: the GUI shell (/) and a
  // semantic /health route (forward-compat; 404 on current dsh but will
  // 200 if a future dsh adds one). Promise.all gives us BOTH answers in
  // one round-trip latency (the two requests run concurrently), and a
  // single 200 on either is enough to call the server healthy.
  return Promise.all([
    probePath('/').catch(() => false),
    probePath('/health').catch(() => false),
  ]).then(([root, health]) => root || health)
}

// ---------- process control ---------------------------------------------------

function pidAlive(pid) {
  if (!Number.isInteger(pid) || pid <= 0) return false
  try { process.kill(pid, 0); return true }
  catch (e) { return e.code === 'EPERM' }
}

function readWebPid() {
  try {
    const n = Number(fs.readFileSync(WEB_PID, 'utf8').trim())
    return Number.isInteger(n) && n > 0 ? n : null
  } catch (_) { return null }
}

function portHasListener(port) {
  // Try to open a TCP connection to 127.0.0.1:port. If the OS refuses
  // (ECONNREFUSED) nothing is listening. A successful connect means a
  // listener is present, regardless of whether it answers HTTP correctly.
  return new Promise((resolve) => {
    const sock = net.createConnection({ host: '127.0.0.1', port: port, timeout: 1500 })
    let settled = false
    const finish = (v) => { if (!settled) { settled = true; try { sock.destroy() } catch (_) {}; resolve(v) } }
    sock.once('connect', () => finish(true))
    sock.once('error',   () => finish(false))
    sock.once('timeout', () => finish(false))
  })
}

/**
 * Ask the platform service to relaunch dsh web.
 *
 * Design intent: the watchdog does NOT replace the platform service
 * that owns dsh web's lifecycle. macOS launchd, Linux systemd, and
 * Windows Task Scheduler all restart dsh web on crash; the doctor
 * merely nudges them when the doctor notices dsh web is gone and the
 * platform service has not (yet) acted.
 *
 * - macOS: launchctl kickstart -k gui/<uid>/<label> restarts the
 *   service. The label is read from the platform plist that the
 *   install step wrote next to the watchdog script.
 * - Linux: systemctl --user restart <unit> restarts the user unit.
 * - Windows: Task Scheduler can be triggered via schtasks /Run.
 *
 * Returns true if a relaunch was successfully issued, false if no
 * platform service is registered (in which case the caller falls back
 * to a direct startWeb() spawn).
 */
function relaunchViaPlatform() {
  const label = readPlatformLabel()
  if (!label) {
    log('INFO', 'no platform label recorded; cannot kickstart')
    return false
  }
  if (process.platform === 'darwin') {
    const uid = process.getuid ? process.getuid() : 501
    const target = 'gui/' + uid + '/' + label
    try {
      cp.execFileSync('launchctl', ['kickstart', '-k', target], { stdio: 'pipe' })
      log('INFO', 'launchctl kickstart -k ' + target + ' issued')
      return true
    } catch (e) {
      log('WARN', 'launchctl kickstart failed: ' + (e.stderr ? e.stderr.toString() : e.message))
      return false
    }
  }
  if (process.platform === 'linux') {
    try {
      cp.execFileSync('systemctl', ['--user', 'restart', label], { stdio: 'pipe' })
      log('INFO', 'systemctl --user restart ' + label + ' issued')
      return true
    } catch (e) {
      log('WARN', 'systemctl restart failed: ' + (e.stderr ? e.stderr.toString() : e.message))
      return false
    }
  }
  if (process.platform === 'win32') {
    try {
      cp.execFileSync('schtasks', ['/Run', '/TN', label], { stdio: 'pipe' })
      log('INFO', 'schtasks /Run /TN ' + label + ' issued')
      return true
    } catch (e) {
      log('WARN', 'schtasks failed: ' + (e.stderr ? e.stderr.toString() : e.message))
      return false
    }
  }
  return false
}

function readPlatformLabel() {
  // The install step writes the dsh web service label to
  // $DSH_HOME/doctor/.doctor-web-label so the watchdog can find it
  // without enumerating the platform's service registry.
  const f = path.join(DOCTOR_DIR, '.doctor-web-label')
  try { return fs.readFileSync(f, 'utf8').trim() || null }
  catch (_) { return null }
}

function killWeb() {
  const pid = readWebPid()
  if (!pid) { log('WARN', 'no recorded web pid; skipping kill'); return false }
  if (!pidAlive(pid)) { log('INFO', 'recorded web pid ' + pid + ' already dead'); return true }
  try { process.kill(pid, 'SIGTERM'); log('INFO', 'SIGTERM → ' + pid); return true }
  catch (e) { log('WARN', 'kill failed: ' + e.message); return false }
}

function startWeb() {
  const dsh = process.env.DSH_BIN || 'dsh'
  const args = ['web', '--port', String(WEB_PORT)]
  if (process.env.DSH_NO_OPEN === '1' || process.env.DSH_NO_OPEN === 'true') args.push('--no-open')
  try {
    const child = cp.spawn(dsh, args, {
      detached: true,
      stdio: ['ignore', fs.openSync(path.join(DOCTOR_DIR, 'logs', 'dsh-web.log'), 'a'), fs.openSync(path.join(DOCTOR_DIR, 'logs', 'dsh-web.log'), 'a')],
      env: Object.assign({}, process.env, { DSH_HOME: DSH_HOME }),
      cwd: DSH_HOME,
    })
    child.unref()
    log('INFO', 'spawned dsh web pid=' + child.pid)
    return child.pid
  } catch (e) {
    log('ERROR', 'spawn failed: ' + e.message)
    return null
  }
}

