/**
 * Stage a user-visible error so the next probe (or the next dsh web
 * boot) can surface it. We do not have a real notification channel
 * from the watchdog, so we drop a marker file the user can find, and
 * log loudly. dsh-doctor's dsh_doctor_status tool also picks this
 * up (in-process).
 */
function notifyUser(reason) {
  const f = path.join(DOCTOR_DIR, '.doctor-user-action-required')
  const stamp = new Date().toISOString() + ' ' + reason + '\n'
  try { fs.appendFileSync(f, stamp, { mode: 0o600 }) } catch (_) {}
  log('ERROR', 'human action required: ' + reason)
  log('ERROR', 'see ' + f + ' (read-only)')
}

/**
 * Move a corrupt cordis.patch.yml aside so dsh web can boot with an
 * empty patch (just dsh-core bundles). The user can re-add their
 * custom rows by hand once dsh web is back up.
 */
function cleanupCorruptPatch() {
  try {
    if (!fs.existsSync(PATCH_F)) return
    const backup = PATCH_F + '.doctor-broken-' + Date.now()
    fs.renameSync(PATCH_F, backup)
    log('WARN', 'corrupt patch moved to ' + backup)
  } catch (e) {
    log('WARN', 'could not move corrupt patch: ' + e.message)
  }
}

/**
 * True disable: find the row whose id: equals pluginId in the
 * profile's cordis.patch.yml, move it out of the patch (into a sibling
 * .doctor-disabled-<id> file so the user can restore it by hand), and
 * atomically rewrite the patch without that row.
 *
 * Until v0.2.22 the "simple path" only WROTE the sibling marker file
 * and never touched cordis.patch.yml — so on restart the broken row was
 * still mounted, the boot tripped over it again, and the recovery
 * eventually escalated to safe-mode. The marker existed but nothing
 * consumed it; this function makes the simple path actually disable.
 */
/**
 * Remove the patch row whose id: equals rowId. A row is one "- id:" line
 * plus its indented continuation lines (name/config/...). Everything that
 * does not belong to the matched row is preserved in order. The row is
 * found by a line-anchored id: match, which matches how the doctor's
 * own bundle rows are written.
 */
function removeRowFromPatch(lines, rowId) {
  const out = []
  let pending = []         // lines of the current row, not yet classified
  let pendingIsMatch = false
  let inRowList = false    // inside an insert: block
  const flush = function () {
    if (pending.length === 0) return
    if (!pendingIsMatch) for (let i = 0; i < pending.length; i++) out.push(pending[i])
    pending = []
    pendingIsMatch = false
  }
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    // NOTE: the tag is String.raw (no escape cooking), so backslash
    // escapes in these regexes reach the generated script as written —
    // the same convention as the PATTERNS table above.
    if (/^-\s+insert\s*:/.test(line)) {
      flush()
      inRowList = true
      out.push(line)
      continue
    }
    if (!inRowList) {
      // Top-level line outside any insert: block — always preserved.
      flush()
      inRowList = false
      out.push(line)
      continue
    }
    if (/^\s+-\s+id\s*:/.test(line)) {
      const m = line.match(/^\s+-\s+id\s*:\s*['"]?([^'"'\s]+)['"]?/)
      flush()
      pending = [line]
      pendingIsMatch = !!(m && m[1] && String(m[1]) === String(rowId))
      continue
    }
    // Continuation of the current row (or a blank line between rows).
    pending.push(line)
    continue
  }
  flush()
  return out
}

function stageDisableRow(pluginId) {
  if (!pluginId) return false
  const safe = String(pluginId).replace(/[^A-Za-z0-9_.\-@/]/g, '_')
  const target = PATCH_F + '.doctor-disabled-' + safe
  try {
    const raw = fs.readFileSync(PATCH_F, 'utf8')
    const lines = raw.split(/\r?\n/)
    const pruned = removeRowFromPatch(lines, pluginId)
    if (pruned.length === lines.length) {
      // Row not found in the patch (it may come from a bundle manifest
      // instead of the user patch). Keep the legacy marker file so a
      // human can trace what the doctor thought was broken.
      const body = '# dsh-doctor auto-disabled (row not found in cordis.patch.yml): ' + pluginId + '\n# Generated ' + new Date().toISOString() + '\n# Remove this file once the plugin is fixed.\n'
      fs.writeFileSync(target, body, { mode: 0o600 })
      log('WARN', 'disable row ' + pluginId + ' not found in ' + PATCH_F + ' — wrote marker only')
      return true
    }
    // Backup the original, write the pruned patch, record the disabled row.
    const backup = PATCH_F + '.doctor-bak-' + Date.now()
    fs.copyFileSync(PATCH_F, backup)
    const body = '# dsh-doctor auto-disabled: ' + pluginId + '\n# Generated ' + new Date().toISOString() + '\n# Original patch backed up at ' + backup + '\n# To re-enable, restore that backup (or re-add the row to ' + PATCH_F + ').\n'
    fs.writeFileSync(target, body, { mode: 0o600 })
    const tmp = PATCH_F + '.doctor-disable.tmp'
    fs.writeFileSync(tmp, pruned.join('\n') + (pruned.length ? '\n' : ''), { mode: 0o600 })
    fs.renameSync(tmp, PATCH_F)
    log('INFO', 'disabled row ' + pluginId + ' from ' + PATCH_F + ' (backup ' + backup + ', record ' + target + ')')
    return true
  } catch (e) {
    log('ERROR', 'stage disable failed: ' + e.message)
    return false
  }
}

function activateSafeMode(allowList) {
  const header = [
    '# dsh-doctor safe-mode patch (auto-generated).',
    '# Activated at ' + new Date().toISOString() + ' by the watchdog.',
    '# Remove this file (or rename to .disabled) to exit safe mode.',
  ].join('\n')
  const rows = allowList.map(function (id) { return '    - id: ' + id + '\n      name: ' + id + '\n      config: {safeMode: true}' })
  // Empty-allow-list sentinel: id AND name must be the sentinel, never
  // the bare word dsh-doctor — cordis resolves the name to the running
  // plugin row, so the old name dsh-doctor silently disabled THIS
  // plugin while safe mode was active (the v0.2.20 bug, which this
  // copy of the generator re-introduced). buildSafeModePatch in
  // src/safe-mode.ts is the reference; a test pins the two
  // byte-for-byte on the rows. (No backticks in this comment: the
  // whole file is a raw template — a backtick ends the string.)
  const body = header + '\n- insert:\n' + (rows.length ? rows.join('\n') + '\n' : '    - id: dsh-doctor-safe-mode-sentinel\n      name: dsh-doctor-safe-mode-sentinel\n      config: {safeModeSentinel: true}\n')
  try { fs.writeFileSync(SAFE_MODE, body, { mode: 0o600 }); log('INFO', 'safe-mode patch written: ' + SAFE_MODE) }
  catch (e) { log('ERROR', 'safe-mode write failed: ' + e.message) }
}

function clearSafeMode() {
  try { fs.unlinkSync(SAFE_MODE); log('INFO', 'safe-mode patch cleared') }
  catch (e) { if (e.code !== 'ENOENT') log('WARN', 'safe-mode clear failed: ' + e.message) }
}

// ---------- main loop ---------------------------------------------------------

let consecutiveFailures = 0
let firstFailureAt = 0
let recoveryAttempts = 0
let lastRecoveryAt = 0
let installedAt = Date.now()
let tickCount = 0
// Emit one heartbeat line every N ticks so a healthy watchdog is
// visibly alive in the log. Heartbeat failures are not errors.
const HEARTBEAT_EVERY_N_TICKS = 10

async function tick() {
  // Hard exit if we were uninstalled.
  try { fs.statSync(INSTALLED) }
  catch (_) { log('INFO', 'installed marker missing — exiting'); cleanup(); process.exit(0) }

  loadConfig()

  // Stamp the last-tick marker so the status tool can tell the user
  // "the watchdog has been alive for N seconds" — much friendlier than
  // "unknown uptime". Best-effort write; never throw out of tick().
  try { fs.writeFileSync(LAST_TICK, String(Date.now())) } catch (_) {}
  tickCount++
  const healthy = await probe()
  if (healthy) {
    if (consecutiveFailures > 0 && firstFailureAt > 0) {
      log('INFO', 'health probe OK — recovered after ' + ((Date.now() - firstFailureAt) / 1000).toFixed(1) + 's')
      // If we entered safe mode, we are now stable; keep safe mode until the
      // user explicitly exits it. The plugin's tool dsh_doctor_safe_mode_exit
      // is the supported way to do that.
    }
    consecutiveFailures = 0
    firstFailureAt = 0
    if (tickCount % HEARTBEAT_EVERY_N_TICKS === 0) {
      const uptimeSec = Math.round((Date.now() - installedAt) / 1000)
      log('INFO', 'health probe OK (heartbeat) uptime=' + uptimeSec + 's ticks=' + tickCount)
    }
    return
  }

  consecutiveFailures += 1

  // Diagnose the kind of failure. The platform service (LaunchAgent /
  // systemd / Task Scheduler) owns dsh web's lifecycle — the doctor
  // does NOT touch it. The doctor observes and reacts within ONE
  // probe cycle (default 2s, not 30s+90s of previous designs).
  //
  // The user-facing latency budget is tight: dsh web serves a GUI,
  // a human is staring at a stalled or empty screen. We want triage
  // to fire on the very first sign of trouble.
  const hasPort = await portHasListener(WEB_PORT)

  if (!hasPort) {
    if (consecutiveFailures === 1) {
      // First failure with empty port. Give the platform service
      // ONE fast window (the next probe, 2s away) to recover on
      // its own. If it does, we'll see the port listening again
      // and skip triage entirely.
      log('WARN', 'health probe failed, port ' + WEB_PORT + ' empty — giving platform service 1 probe to recover')
      return
    }
    // 2nd consecutive failure with empty port: platform service
    // cannot recover dsh web. Triage now.
    log('WARN', 'platform service failed to recover dsh web after ' + consecutiveFailures + ' probes — entering crash-loop triage')
    if (firstFailureAt === 0) firstFailureAt = Date.now()
    const elapsed = Date.now() - firstFailureAt
    if (recoveryAttempts >= 3 && (Date.now() - lastRecoveryAt) < 5 * 60 * 1000) {
      log('WARN', 'recovery rate-limited — will retry next tick')
      return
    }
    return triageAndDisable(elapsed)
  }

  // Port has a listener but health probe is failing → dsh web is
  // alive but broken. 1 failure is enough — the user is staring at
  // a stalled GUI; we don't make them wait 90s for a 3-failure
  // threshold.
  if (consecutiveFailures === 1) {
    log('WARN', 'first probe failure with port listening — dsh web alive but broken; reading log for triage')
  }
  if (firstFailureAt === 0) firstFailureAt = Date.now()
  const elapsed2 = Date.now() - firstFailureAt
  if (recoveryAttempts >= 3 && (Date.now() - lastRecoveryAt) < 5 * 60 * 1000) {
    log('WARN', 'recovery rate-limited — will retry next tick')
    return
  }
  log('WARN', 'triaging dsh web failure now (no ' + CFG.healthFailuresToRecover + '-failure wait — user latency budget)')
  return triageAndDisable(elapsed2)
}

/**
 * Read dsh web's log, identify the broken plugin (if any), and write
 * a disable row for it. The platform service will then restart dsh
 * web with the broken plugin disabled.
 */
function triageAndDisable(elapsed) {
  const webLog = path.join(DOCTOR_DIR, 'logs', 'dsh-web.log')
  // Streaming tail — see tailFileByLines above. Honours CFG.triageLogLines
  // so operators can widen / narrow the window without editing code.
  const want = Math.max(50, Math.min(50000, CFG.triageLogLines | 0))
  const lines = tailFileByLines(webLog, want)
  const plan = triage(lines)
  log('INFO', 'triage: matched=' + plan.matched + ' kind=' + plan.kind + (plan.id ? ' id=' + plan.id : ''))

  if (elapsed > CFG.recoveryBudgetMs) {
    log('WARN', 'recovery budget exhausted (' + elapsed + 'ms > ' + CFG.recoveryBudgetMs + 'ms) — staging safe-mode')
    activateSafeMode(CFG.safeModeBundles)
    recoveryAttempts += 1
    lastRecoveryAt = Date.now()
    return
  }

  if (plan.kind === 'kill-pid-and-restart') {
    // A port conflict: an orphan pid is holding the listener so a
    // fresh web process cannot bind. Killing the recorded pid is the
    // exact fix — the platform service then re-pulls dsh web with
    // nothing to conflict against. Disabling a row (or safe-mode)
    // here would demote a working plugin for no reason.
    const killed = killWeb()
    if (!killed) {
      // No recorded pid / kill failed: fall through to safe-mode so
      // at least something changes and the platform service retries.
      log('WARN', 'kill-pid-and-restart: kill failed; falling back to safe-mode')
      activateSafeMode(CFG.safeModeBundles)
    } else {
      log('INFO', 'kill-pid-and-restart: orphan pid killed; waiting for platform service to restart dsh web')
    }
  } else if (plan.kind === 'notify-user') {
    // The doctor cannot fix this; the human must. Log loudly so it
    // surfaces in dsh_doctor_diagnose and any operator tailing
    // the log file.
    log('ERROR', 'UNRECOVERABLE — human action required: ' + plan.reason)
    notifyUser(plan.reason)
  } else if (plan.kind === 'cleanup-and-restart') {
    log('WARN', 'cleanup action: ' + plan.reason)
    cleanupCorruptPatch()
    log('INFO', 'corrupt patch moved aside; waiting for platform service to restart dsh web')
  } else if (plan.kind === 'safe-mode') {
    activateSafeMode(CFG.safeModeBundles)
  } else if (plan.kind === 'disable-row' && plan.id) {
    stageDisableRow(plan.id)
  } else {
    // Nothing specific to disable — fall back to safe-mode.
    log('WARN', 'no specific plugin identified; activating safe-mode')
    activateSafeMode(CFG.safeModeBundles)
  }

  recoveryAttempts += 1
  lastRecoveryAt = Date.now()
  // Reset failure tracking so we wait for the next launchd pull
  // to actually run with the disabled plugin.
  consecutiveFailures = 0
  firstFailureAt = 0
  log('INFO', 'triage action staged; waiting for platform service to restart dsh web')
}

function loop() {
  // Use a per-tick setTimeout inside finally so a rejected or thrown tick
  // can never break the loop. Previous setTimeout-after-then chain silently
  // died if tick() returned a never-resolving promise (observed live:
  // 5 minutes of 0% CPU on PID 71994 after a healthy dsh web restart).
  // finally guarantees the next tick is always scheduled, even when
  // tick() throws synchronously. The arrow functions are written
  // without TypeScript annotations on purpose: WATCHDOG_STANDALONE_BODY
  // is a tagged-template string that tsc parses byte by byte, so any
  // return-type annotation like '() => void' would leak into the
  // generated script and break the runtime parse.
  const run = () => {
    tick()
      .catch((e) => log('ERROR', 'tick: ' + (e && e.message ? e.message : String(e))))
      .finally(() => setTimeout(run, CFG.healthIntervalMs))
  }
  run()
}

function cleanup() {
  try { fs.unlinkSync(PID_F) } catch (_) {}
  try { fs.unlinkSync(LAST_TICK) } catch (_) {}
  try { fs.unlinkSync(STARTED) } catch (_) {}
}

function singleInstance() {
  try {
    const old = Number(fs.readFileSync(PID_F, 'utf8').trim())
    if (Number.isInteger(old) && old > 0 && pidAlive(old)) {
      log('WARN', 'another watchdog already running pid=' + old + ' — exiting')
      process.exit(0)
    }
  } catch (_) {}
  fs.writeFileSync(PID_F, String(process.pid), { mode: 0o600 })
  // Stamp the start-time marker so the plugin's status tool can report
  // a real uptime. Written ONCE per process lifetime (before the first
  // tick), removed by cleanup() on clean shutdown or uninstall.
  try { fs.writeFileSync(STARTED, String(Date.now()), { mode: 0o600 }) } catch (_) {}
  // Update the in-memory installedAt that the heartbeat log uses.
  installedAt = Date.now()
}

function handleSignal(sig) {
  log('INFO', 'received ' + sig + ' — exiting')
  cleanup()
  process.exit(0)
}

process.on('SIGINT',  () => handleSignal('SIGINT'))
process.on('SIGTERM', () => handleSignal('SIGTERM'))
process.on('SIGHUP',  () => { log('INFO', 'SIGHUP — reloading config'); loadConfig() })

log('INFO', 'watchdog started pid=' + process.pid + ' home=' + DSH_HOME + ' port=' + WEB_PORT)
singleInstance()
loop()
